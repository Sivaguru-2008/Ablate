"""Emit pytest files from a finished run (pattern after agentrial's pytest
plugin: statistical checks surfaced as ordinary pytest tests).

Layer A (deterministic): for every scenario, each recorded trajectory of the
arm is replayed into the deterministic world (exact observation and state-hash
match required) and the contracts are re-evaluated on the replay; a majority
of the k trials must satisfy every contract.

Layer B (statistical): non-inferiority of the arm against its reference
(base; the A/A replicate when the arm is base): the one-sided level-alpha
upper bound on the violation-rate difference must be below delta.
"""

from __future__ import annotations

from pathlib import Path

from .. import fidelity
from ..oracle import contracts
from ..plan import load
from ..results import read_jsonl
from ..scenarios import load_scenarios
from ..verdict import _cmp, tabulate
from ..world.retail.tools import RetailWorld

TEMPLATE = '''# Generated by `ablate pytest-gen` from run {run_name} (plan {plan_hash}). Do not edit.
# Layer A: deterministic replay + per-scenario majority contract check.
# Layer B: statistical non-inferiority of arm {arm!r} vs {ref!r} (delta = {delta}).
from pathlib import Path

import pytest

from ablate.report.pytest_gen import layer_a, layer_b, scenario_ids

RUN = Path(r"{run_dir}")
ARM = {arm!r}
REF = {ref!r}


@pytest.mark.parametrize("scenario", scenario_ids(RUN))
def test_layer_a_contracts(scenario):
    bad, total, detail = layer_a(RUN, ARM, scenario)
    assert total > 0, "no valid trials recorded"
    assert bad <= total // 2, f"{{bad}}/{{total}} trials violate a contract: {{detail}}"


def test_layer_b_non_inferiority():
    diff, upper, delta = layer_b(RUN, ARM, REF)
    assert upper < delta, f"violation rate {{diff:+.3f}} vs {{REF}}, upper bound {{upper:+.3f}} >= delta {{delta}}"
'''


_CACHE: dict = {}


def _load(run: Path):
    key = str(Path(run).resolve())
    if key not in _CACHE:
        plan = load(Path(run))
        results = read_jsonl(Path(run) / "results.jsonl")
        scn = {s["id"]: s for s in load_scenarios(Path(run) / "scenarios.yaml")}
        _CACHE[key] = (plan, results, scn)
    return _CACHE[key]


def scenario_ids(run: Path) -> list[str]:
    return list(_load(run)[0].scenarios)


def layer_a(run: Path, arm: str, scenario: str) -> tuple[int, int, str]:
    plan, results, scn = _load(run)
    initial = RetailWorld().snapshot()
    bad = total = 0
    notes = []
    for r in results:
        if r.arm != arm or r.scenario != scenario or r.status != "OK":
            continue
        total += 1
        rep = fidelity.replay(r.trace)
        if not rep.ok or rep.state_hash != r.state_hash:
            raise AssertionError(f"replay of trial {r.trial} does not match the recording")
        found = contracts.evaluate(scn[scenario], initial=initial, final=rep.world.snapshot(), final_hash=rep.state_hash,
                                   call_log=rep.world.call_log, effect_log=rep.world.effect_log,
                                   structured_output=r.structured_output)
        if found:
            bad += 1
            notes.append(f"t{r.trial}: {found[0].contract}")
    return bad, total, ", ".join(notes[:5])


def layer_b(run: Path, arm: str, ref: str) -> tuple[float, float, float]:
    plan, results, _ = _load(run)
    counts, _ = tabulate(plan, results)
    c = _cmp(counts, arm, ref, plan, salt=7)
    return c.diff, c.upper(plan.alpha), plan.delta


def generate(run_dir: Path, arm: str, out_dir: Path) -> Path:
    plan = load(run_dir)
    if arm not in plan.arm_names:
        raise ValueError(f"arm {arm!r} not in plan: {plan.arm_names}")
    ref = "aa" if arm == "base" else "base"
    out_dir.mkdir(parents=True, exist_ok=True)
    safe = arm.replace("+", "_plus_").replace("-", "_minus_").replace(".", "_")
    path = out_dir / f"test_ablate_{safe}.py"
    path.write_text(TEMPLATE.format(run_name=run_dir.name, plan_hash=plan.plan_hash[:12], arm=arm, ref=ref,
                                    delta=plan.delta, run_dir=str(run_dir.resolve())), encoding="utf-8")
    return path


__all__ = ["generate", "layer_a", "layer_b", "scenario_ids"]
